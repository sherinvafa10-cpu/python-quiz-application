questions = [
    ["What is the capital of India?", "Delhi"],
    ["Which language are we learning?", "Python"],
    ["What is 10 + 5?", "15"],
    ["Which symbol is used for comments in Python?", "#"]
]

score = 0
print("==== PYTHON QUIZ ====")
for question in questions:
  print("\n", question[0])
  answer = input("Your answer: ")
  if answer.lower() == question[1].lower():
    print("Correct!")
    score += 1
  else:
    print("Incorrect!")
print("\n==== RESULT ====")
print("Your score:", score, "/", len(questions))
if score == len(questions):
  print("Congratulations! You got all the questions correct.")
elif score >= len(questions) // 2:
  print("Good job! You got", score, "out of", len(questions), "questions correct.")
else:
  print("Better luck next time! You got", score, "out of", len(questions), "questions correct.")